export type ExtraIconName = keyof typeof EXTRA;
export type AnyIconName = IconName | ExtraIconName;

/** A line icon from the shared set or this file's extras (decorative, aria-hidden). */
export function CIcon({ name, size = 20, className }: { name: AnyIconName; size?: number; className?: string }) {
  if (!(name in EXTRA)) return <Icon name={name as IconName} size={size} className={className} />;
  return (
    <svg
      className={className ? `bh-icon ${className}` : "bh-icon"}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {EXTRA[name as ExtraIconName]}
    </svg>
  );
}

