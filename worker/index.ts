/**
 * The one Worker for https://bodhiraai.com (replaces the legacy Nginx server
 * block; see ../DEPLOY.md):
 *   /api/v1/*, /webhooks/*  -> the API on Elastic Beanstalk (API_ORIGIN)
 *   /media/*, /cloud/*, /assets/**.mp4 -> legacy files copied to R2 (LEGACY_FILES)
 *   /files/*                -> private uploads (PRIVATE_FILES), signed links only
 *   everything else         -> the Next.js app, run in this Worker by OpenNext
 * Files in public/ and _next/static are Workers static assets: Cloudflare serves
 * them before this code runs (headers from .open-next/assets/_headers,
 * scripts/cf-assets-headers.mjs).
 * The visitor's address goes along as X-Client-IP with the proxy key derived
 * from APP_SECRET (worker/app-secret.ts), which the API believes (bodhiraai-api/src/common/http/client-ip.ts).
 */
// @ts-expect-error `.open-next/worker.js` is generated by `npm run cf:build` (untyped JS).
import openNext from '../.open-next/worker.js';
import { deriveKey } from './app-secret';
import { limitBody, overBodyLimit } from './body-limit';
import { keyFromPath, verifyFileLink } from './file-sig';
import { legacyFileKey } from './legacy-key';

// The Durable Objects behind the Next cache (open-next.config.ts).
// @ts-expect-error generated by `npm run cf:build` (untyped JS).
export { DOQueueHandler, DOShardedTagCache } from '../.open-next/worker.js';

export interface Env {
  /** Static assets (.open-next/assets). */
  ASSETS: Fetcher;
  LEGACY_FILES: R2Bucket;
  /** Private uploads (avatars, logos, lesson files, submissions); the API's R2_PRIVATE_BUCKET. */
  PRIVATE_FILES: R2Bucket;
  /** Next cache (open-next.config.ts). */
  NEXT_INC_CACHE_R2_BUCKET: R2Bucket;
  NEXT_TAG_CACHE_DO_SHARDED: DurableObjectNamespace;
  NEXT_CACHE_DO_QUEUE: DurableObjectNamespace;
  /** This Worker, for the Next cache's revalidation and proxy.ts (lib/self-fetch.ts). */
  WORKER_SELF_REFERENCE: Fetcher;
  /** The API's origin, without a path (https://api.bodhiraai.com). */
  API_ORIGIN: string;
  SITE_URL: string;
  /** Read by the Next server code; derived below when not set. */
  API_URL?: string;
  LEGACY_URL?: string;
  /** The one secret, the same value as the API's APP_SECRET (a Worker secret). */
  APP_SECRET: string;
}

type Handler = { fetch(request: Request, env: unknown, ctx: ExecutionContext): Promise<Response> };
const next = openNext as Handler;

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const path = url.pathname;
    const client = request.headers.get('cf-connecting-ip') ?? '';

    if (path.startsWith('/api/v1/') || path.startsWith('/webhooks/')) {
      const headers = new Headers(request.headers);
      headers.set('X-Client-IP', client);
      headers.set('X-Proxy-Secret', await deriveKey(env.APP_SECRET, 'proxy'));
      return fetch(
        new Request(`${env.API_ORIGIN}${path}${url.search}`, {
          method: request.method,
          headers,
          body: request.body,
          redirect: 'manual',
        }),
      );
    }

    if (path === '/files' || path.startsWith('/files/')) {
      return privateFile(request, env, url);
    }

    if (overBodyLimit(request.method, path, request.headers.get('content-length'))) {
      return new Response('Payload Too Large', { status: 413 });
    }

    const legacyKey = legacyFileKey(path);
    if (legacyKey === null) return new Response('Not Found', { status: 404 });
    if (legacyKey) return serveFile(request, env.LEGACY_FILES, legacyKey);

    // Set here, so a visitor can't supply their own; api() passes it to the API.
    const headers = new Headers(request.headers);
    headers.set('X-Client-IP', client);
    return next.fetch(new Request(request, { headers, body: limitBody(request.body, path) }), await nextEnv(env), ctx);
  },
} satisfies ExportedHandler<Env>;

/**
 * What the Next server code reads from process.env (OpenNext copies every
 * string binding into it on the isolate's first request): the API's base URL
 * for server-side calls (lib/api.ts, lib/site-api.ts, proxy.ts), and the site
 * itself for relative legacy files, which this Worker serves from R2, and the
 * proxy key (lib/proxy-secret.ts). APP_SECRET itself is not passed on: the Next
 * code gets only the derived PROXY_SECRET. SITE_URL passes through as it is.
 */
async function nextEnv(env: Env): Promise<Omit<Env, 'APP_SECRET'> & { PROXY_SECRET: string }> {
  const { APP_SECRET, ...rest } = env;
  return {
    ...rest,
    API_URL: env.API_URL || `${env.API_ORIGIN.replace(/\/+$/, '')}/api/v1`,
    LEGACY_URL: env.LEGACY_URL || env.SITE_URL,
    PROXY_SECRET: await deriveKey(APP_SECRET, 'proxy'),
  };
}

/** GET/HEAD of an R2 object with byte ranges (video seeking), as legacy's MediaController::stream. */
async function serveFile(
  request: Request,
  bucket: R2Bucket,
  key: string,
  /** Final say on the response headers (private files). */
  finish?: (headers: Headers) => void,
): Promise<Response> {
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    return new Response('Method Not Allowed', {
      status: 405,
      headers: { Allow: 'GET, HEAD' },
    });
  }
  const rangeHeader = request.headers.get('range');
  let object: R2Object | R2ObjectBody | null;
  try {
    object = await bucket.get(key, {
      range: request.headers,
      onlyIf: request.headers,
    });
  } catch (e) {
    // R2 rejects a range it can't satisfy; anything else is a real error.
    if (rangeHeader) return new Response(null, { status: 416 });
    throw e;
  }
  if (!object) return new Response('Not Found', { status: 404 });
  // A range that starts past the end is 416, not the whole file (R2 may clamp it).
  const start = /^bytes=(\d+)-/.exec(rangeHeader ?? '');
  if (start && Number(start[1]) >= object.size) {
    return new Response(null, { status: 416, headers: { 'Content-Range': `bytes */${object.size}` } });
  }

  const headers = new Headers();
  object.writeHttpMetadata(headers);
  headers.set('ETag', object.httpEtag);
  headers.set('Accept-Ranges', 'bytes');
  hardenFile(headers);
  finish?.(headers);
  if (!('body' in object)) return new Response(null, { status: 304, headers });

  let status = 200;
  const range = object.range;
  if (range && request.headers.has('range')) {
    // R2Range is {offset, length?}, {offset?, length}, or {suffix}; absent
    // fields may be present as undefined, so test values, not keys.
    const r = range as { offset?: number; length?: number; suffix?: number };
    const offset =
      r.suffix !== undefined
        ? Math.max(0, object.size - r.suffix)
        : (r.offset ?? 0);
    const length =
      r.suffix !== undefined
        ? object.size - offset
        : Math.min(r.length ?? object.size - offset, object.size - offset);
    status = 206;
    headers.set(
      'Content-Range',
      `bytes ${offset}-${offset + length - 1}/${object.size}`,
    );
    headers.set('Content-Length', String(length));
  } else {
    headers.set('Content-Length', String(object.size));
  }
  return new Response(request.method === 'HEAD' ? null : object.body, {
    status,
    headers,
  });
}

/**
 * GET/HEAD /files/<key>?exp&sig: a private upload behind a short-lived link
 * the API signed (file-sig.ts). Anything wrong with the link is the same 403,
 * so a probe can't tell a forbidden key from a bad signature; a valid link to
 * a missing object is a 404. The browser may keep the file only until the
 * link expires (at most an hour), never in a shared cache.
 * security: not in legacy
 */
async function privateFile(request: Request, env: Env, url: URL): Promise<Response> {
  if (request.method !== 'GET' && request.method !== 'HEAD') {
    return new Response('Method Not Allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
  }
  const key = keyFromPath(url.pathname.slice('/files/'.length));
  const check =
    key === null
      ? { ok: false as const }
      : await verifyFileLink(await deriveKey(env.APP_SECRET, 'file-urls'), key, url.searchParams.get('exp'), url.searchParams.get('sig'));
  if (!check.ok || key === null) {
    return Response.json(
      { message: 'Link expired or invalid.' },
      { status: 403, headers: { 'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff' } },
    );
  }
  const maxAge = Math.max(0, Math.min(check.exp - Math.floor(Date.now() / 1000), 3600));
  return serveFile(request, env.PRIVATE_FILES, key, (headers) => {
    headers.set('Content-Disposition', 'inline');
    headers.set('Cache-Control', `private, max-age=${maxAge}`);
    headers.set('Referrer-Policy', 'no-referrer');
  });
}

/**
 * Uploaded files are user content on the site's own origin. Never let a
 * browser guess a type (an HTML or SVG file renamed .jpg), and give anything
 * that is not a PDF or a video/audio file an empty, sandboxed policy: no
 * scripts, no origin, so a stray HTML/SVG upload can't act as the site.
 * Images show inline under it. PDFs and media are left to nosniff alone:
 * Chrome's PDF viewer refuses to load a PDF served with `sandbox`, and these
 * types can't run script in our origin. (security: not in legacy)
 */
function hardenFile(headers: Headers): void {
  headers.set('X-Content-Type-Options', 'nosniff');
  const type = (headers.get('Content-Type') ?? '').split(';')[0].trim().toLowerCase();
  const viewer = type === 'application/pdf' || type.startsWith('video/') || type.startsWith('audio/');
  if (!viewer) headers.set('Content-Security-Policy', "default-src 'none'; sandbox");
}
